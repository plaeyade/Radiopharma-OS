"""
Puertos del Auth Service.
"""
from __future__ import annotations

from typing import Optional, Protocol

from app.domain.entities import RefreshClaims, RefreshToken, TokenClaims, User


class UserRepository(Protocol):
    async def save(self, user: User) -> User: ...
    async def update(self, user: User) -> User: ...
    async def get(self, username: str) -> Optional[User]: ...
    async def list(self) -> list[User]: ...
    async def count(self) -> int: ...


class PasswordHasher(Protocol):
    def hash(self, password: str) -> str: ...
    def verify(self, password: str, password_hash: str) -> bool: ...


class TokenIssuer(Protocol):
    def issue(self, user: User, ttl_minutes: int) -> str: ...
    def verify(self, token: str) -> TokenClaims: ...
    def issue_refresh(self, username: str, ttl_minutes: int) -> tuple[str, str, int, int]: ...
    def verify_refresh(self, token: str) -> RefreshClaims: ...
    def issue_mfa_challenge(self, username: str, ttl_minutes: int = 5) -> str: ...
    def verify_mfa_challenge(self, token: str) -> str: ...   # devuelve sub


class RefreshTokenStore(Protocol):
    """Registro servidor de refresh tokens (permite revocación)."""

    async def save(self, token: RefreshToken) -> RefreshToken: ...

    async def get(self, jti: str) -> Optional[RefreshToken]: ...

    async def revoke(self, jti: str) -> bool: ...

    async def revoke_all_for_user(self, username: str) -> int: ...
